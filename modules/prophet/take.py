"""modules/prophet/melodee/ from Melodee's own tree (github.com/keremimo/melodee, Kerem Kilic / Ellic Studio): its
PROPHET engine (firmware/src/eng_prophet_test.c, despite the name the playable Prophet-5 Rev 4 prototype), its native
patch format (prophet_patch.c), its float maths (x0x/fastmath.h) and its performance switches unchanged, but for what a
module's memory needs: the patch array's .pool section (Melodee's second RAM region) is gone, a module's RAM is one
region the host clears; the sample kernels' .dsp_text (Melodee's RAM code) is the module's .ram_text; the wheel
kernel's dispatcher (.audio_text) stays in flash. The engine's lookup tables are made here, by the formulas of
Melodee's tools/gen_tables.py (P5_* and what they use: the pitch table, ENV_LIN), as p5_tables.h: the per-sample
ones (the filter's coefficients, tanh, 2^x) in RAM (.data), the rest in flash.

Sequential's factory programs (Melodee's assets/prophet5-factory, its melodee_prophet_factory.h) are NOT taken: Melodee
carries them as "Sequential's (no licence granted)". The engine's factory hook sees none (melodee_prophet_factory.h
here: no programs); a player sends their own copy of a bank to the module instead (prophet_module.c, HB_F_DATA).

The adapter under it (Melodee's track / voice / allocator, the second core) is prophet_module.c. Run it again on a
new Melodee:
    modules/prophet/take.py ~/src/melodee        (Melodee e9b07b4, branch next)"""
import math
import shutil
import sys
from pathlib import Path

src = Path(sys.argv[1])
fw = src / "firmware/src"
out = Path(__file__).resolve().parent / "melodee"
(out / "x0x").mkdir(parents=True, exist_ok=True)
for f in ["eng_prophet_test.c", "prophet_patch.c", "x0x/fastmath.h", "performance_options.h"]:
    shutil.copy(fw / f, out / f)
shutil.copy(src / "LICENSE", out / "LICENSE")


def sub(name, old, new, count=1):
    t = (out / name).read_text()
    assert t.count(old) == count, (name, old, t.count(old))
    (out / name).write_text(t.replace(old, new))


E = "eng_prophet_test.c"
sub(E, 'static p5_patch_t p5_patch[NPART] __attribute__((section(".pool")));',
    "static p5_patch_t p5_patch[NPART];   /* fm1-dock: one RAM region (take.py) */")
sub(E, 'section(".dsp_text")', 'section(".ram_text.p5")', count=4)
sub(E, '__attribute__((noinline,section(".audio_text")))', "__attribute__((noinline))")
for f in out.rglob("*.[ch]"):
    t = f.read_text()
    assert ".pool" not in t and ".dsp_text" not in t and ".audio_text" not in t, f

# ---- the tables (Melodee's tools/gen_tables.py, FS 44100, CTL 32, P5_OVERSAMPLE 1)
FS, CTL = 44100, 32


def arr(name, ctype, vals, per=8, ram=False):
    sec = ' __attribute__((section(".data.p5_tables")))' if ram else ""   # (RAM, not XIP flash: as Melodee's TABLE_RAM)
    o = [f"static {'' if ram else 'const '}{ctype} {name}[{len(vals)}]{sec} = {{"]
    for i in range(0, len(vals), per):
        o.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return o + ["};"]


L = ["/* generated by modules/prophet/take.py, by the formulas of Melodee's tools/gen_tables.py: do not edit */",
     "/* SPDX-License-Identifier: GPL-3.0-only */", "#pragma once", "#include <stdint.h>",
     f"#define FS {FS}", f"#define CTL {CTL}", ""]
inc = [min(int(440.0 * 2 ** ((p / 16 - 69) / 12) / FS * 2 ** 32), 0x7FFFFFFF) for p in range(128 * 16)]
oct_ = inc[1856:2048]
assert all(inc[q] == oct_[(q + 64) % 192] >> (10 - (q + 64) // 192) for q in range(2048))
assert all((q + 64) * 21846 >> 22 == (q + 64) // 192 for q in range(2048))
L += arr("PITCH_OCT", "uint32_t", oct_)
L += ["/* phase increment of pitch p in 1/16 semitone, 0..2047 (MIDI 0..127): 440 Hz * 2^((p / 16 - 69) / 12) */",
      "static inline uint32_t pitch_inc(uint32_t p)", "{",
      "    uint32_t i = p + 64u, o = (i * 21846u) >> 22;     /* i / 192: the octave above PITCH_OCT's - 10 */",
      "    return PITCH_OCT[i - o * 192u] >> (10u - o);", "}"]
ms = [1.0 * (10000 ** (v / 127)) for v in range(128)]
L += arr("ENV_LIN", "uint32_t", [max(1, int((1 << 24) * CTL / (m * FS / 1000))) for m in ms])
fc = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
L += [f"#define P5_KEYTRACK_HALF_Q7 {round(128 * 256 * 127 * math.log(2) / (2 * 192 * math.log(fc[-1] / fc[0])))}"]


def p5_lfo_hz(v):
    x = -3.1005 + 0.05387 * v
    if v > 100:
        x += (math.log(500) - (-3.1005 + 0.05387 * 127)) * ((v - 100) / 27) ** 2
    if v < 20:
        x -= (-3.1005 - math.log(.022)) * ((20 - v) / 20) ** 2
    return math.exp(x)


L += arr("P5_LFO_INC", "uint32_t", [int(p5_lfo_hz(v) / FS * 2**32) for v in range(128)])
L += arr("P5_AMOUNT", "float", [f"{(v / 127) ** 1.737:.9e}f" for v in range(128)], 6)
p5ms = [10000 ** (v / 127) for v in range(128)]
L += arr("P5_ENV_ATK", "float", [f"{CTL / (m * FS / 1000):.9e}f" for m in p5ms], 6)
L += arr("P5_ENV_EXP", "float", [f"{1 - math.exp(-CTL / (m / 1000 * FS)):.9e}f" for m in p5ms], 6)
L += arr("P5_ENV_SSM", "float", [f"{CTL / (3.6 * m * FS / 1000):.9e}f" for m in p5ms], 6)
L += ["/* per sample, in RAM */"]
L += arr("P5_TPT_G", "float", [f"{math.tan(math.pi * f / FS) / (1 + math.tan(math.pi * f / FS)):.9e}f" for f in fc], 6, ram=True)
L += arr("P5_TANH", "float", [f"{math.tanh(i / 128):.9e}f" for i in range(1025)], 6, ram=True)
L += arr("P5_EXP2", "float", [f"{2 ** (i / 512):.9e}f" for i in range(514)], 6, ram=True)
(out / "p5_tables.h").write_text("\n".join(L) + "\n")
print("prophet/melodee/: taken from", src)
