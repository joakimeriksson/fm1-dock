import importlib.util
import shutil
import sys
from pathlib import Path

src = Path(sys.argv[1]).resolve()
fw = src / "firmware/src"
out = Path(__file__).resolve().parent / "melodee"
(out / "x0x").mkdir(parents=True, exist_ok=True)
for f in ["eng_fm6.c", "fm6_core.c", "eng_fm6_rom.h", "x0x/fastmath.h", "performance_options.h"]:
    shutil.copy(fw / f, out / f)
shutil.copy(src / "LICENSE", out / "LICENSE")
shutil.copy(src / "LICENSES/Apache-2.0-msfa.txt", out / "Apache-2.0-msfa.txt")


def sub(name, old, new, count=1):
    t = (out / name).read_text()
    assert t.count(old) == count, (name, old, t.count(old))
    (out / name).write_text(t.replace(old, new))


sub("fm6_core.c", 'section(".dsp_text")', 'section(".ram_text.fm6")', count=10)
sub("eng_fm6.c", 'section(".dsp_text")', 'section(".ram_text.fm6")', count=2)
sub("eng_fm6.c", '__attribute__((noinline,section(".audio_text")))', "__attribute__((noinline))")
for f in out.rglob("*.[ch]"):
    t = f.read_text()
    assert ".pool" not in t and ".dsp_text" not in t and ".audio_text" not in t, f


def load(name):
    spec = importlib.util.spec_from_file_location(name, src / "tools" / f"{name}.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


gt = load("gen_tables")
L = ["/* generated by modules/fm6/take.py: Melodee's tools/gen_tables.py fm6_tables(), as it is: do not edit */",
     "/* SPDX-License-Identifier: GPL-3.0-only */", "#pragma once", "#include <stdint.h>",
     f"#define FS {gt.FS}", f"#define CTL {gt.CTL}", ""]
(out / "fm6_tables.h").write_text("\n".join(L + gt.fm6_tables()) + "\n")
load("gen_fm6_patches").main(str(out / "melodee_fm6.h"))
print("fm6/melodee/: taken from", src)
